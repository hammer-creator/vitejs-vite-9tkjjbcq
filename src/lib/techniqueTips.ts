export function getTechniqueTips(exerciseName: string): string[] {
  const key = exerciseName.toLowerCase().trim();
  if (TIPS_DB[key]) return TIPS_DB[key].rules;

  // Try partial match
  for (const dbKey of Object.keys(TIPS_DB)) {
    if (key.includes(dbKey) || dbKey.includes(key)) {
      return TIPS_DB[dbKey].rules;
    }
  }

  return DEFAULT_TIPS.rules;
}
